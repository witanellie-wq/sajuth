--  왜 필요한가:
--    고와비 건인데 예약장부에 현장 결제(QR 등)로 적힌 경우가 있습니다.
--    그러면 수수료 20% 를 안 떼고 커미션이 더 나갑니다.
--    반대로 현장 건이 고와비로 적히면 커미션이 덜 나갑니다.
--    예약장부 원본을 건드리지 않고 이 건만 바꿔 잡을 수 있게 합니다.
--
--    비워 두면 예약장부에 적힌 대로 갑니다 (지금까지와 같습니다).
--      'gw' = 고와비 (수수료 뺌)   ·   'on' = 현장 (수수료 안 뗌)
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.staff_comm_override
  add column if not exists pay_kind text;

-- ══ 확인 ══
select coalesce(pay_kind,'(예약장부 그대로)') as "결제 경로", count(*) as "건수"
from public.staff_comm_override group by 1 order by 2 desc;
